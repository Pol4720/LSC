/**
 * POST a sealed envelope to an HTTP relay (Vercel function / Cloudflare Worker
 * / any endpoint that commits to the repo). Used when a relay URL is configured;
 * the app degrades gracefully to link/download delivery when it is not.
 */
export async function postToRelay(relayUrl, envelope, { timeoutMs = 15000 } = {}) {
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), timeoutMs);
  try {
    const res = await fetch(relayUrl, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(envelope),
      signal: ctrl.signal,
    });
    const body = await res.json().catch(() => ({}));
    if (!res.ok) throw new GitHubError(body.error || `Relay HTTP ${res.status}`, res.status, body);
    return body;
  } finally {
    clearTimeout(timer);
  }
}
