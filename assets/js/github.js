/* =========================================================================
   LSC · GitHub storage adapter
   ---------------------------------------------------------------------------
   Treats a GitHub repository as the database:
     data/submissions/<id>.json   sealed client records (public-safe)
     data/index.json              PII-free manifest, regenerated by CI
     data/config/advisor-key.json advisor public key
     data/crm/<id>.json           advisor-side CRM overlay (also sealed)

   Reads work anonymously through raw.githubusercontent.com.
   Writes need a fine-grained PAT with "Contents: Read and write" on this repo,
   stored only in the advisor's browser (never committed, never in a URL).
   ========================================================================= */

const API = 'https://api.github.com';
const RAW = 'https://raw.githubusercontent.com';

export class GitHubError extends Error {
  constructor(message, status, body) {
    super(message);
    this.name = 'GitHubError';
    this.status = status;
    this.body = body;
  }
}

const utf8ToB64 = (str) => {
  const bytes = new TextEncoder().encode(str);
  let s = '';
  for (let i = 0; i < bytes.length; i += 0x8000) s += String.fromCharCode.apply(null, bytes.subarray(i, i + 0x8000));
  return btoa(s);
};

const b64ToUtf8 = (b64) => {
  const bin = atob(String(b64).replace(/\s/g, ''));
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  return new TextDecoder().decode(bytes);
};

export class GitHubRepo {
  /**
   * @param {{owner:string, repo:string, branch?:string, token?:string|null,
   *          fetchImpl?:Function}} cfg
   */
  constructor(cfg = {}) {
    this.owner = cfg.owner || '';
    this.repo = cfg.repo || '';
    this.branch = cfg.branch || 'main';
    this.token = cfg.token || null;
    this.fetch = cfg.fetchImpl || ((...a) => globalThis.fetch(...a));
    this.rate = { limit: null, remaining: null, reset: null };
  }

  get slug() { return `${this.owner}/${this.repo}`; }
  get configured() { return Boolean(this.owner && this.repo); }
  get canWrite() { return Boolean(this.configured && this.token); }

  headers(extra = {}) {
    const h = { Accept: 'application/vnd.github+json', 'X-GitHub-Api-Version': '2022-11-28', ...extra };
    if (this.token) h.Authorization = `Bearer ${this.token}`;
    return h;
  }

  async request(path, opts = {}) {
    const url = path.startsWith('http') ? path : `${API}${path}`;
    const res = await this.fetch(url, {
      ...opts,
      headers: this.headers(opts.headers || {}),
    });
    this.rate = {
      limit: num(res.headers.get('x-ratelimit-limit')),
      remaining: num(res.headers.get('x-ratelimit-remaining')),
      reset: num(res.headers.get('x-ratelimit-reset')),
    };
    const text = await res.text();
    let body = null;
    try { body = text ? JSON.parse(text) : null; } catch { body = text; }
    if (!res.ok) {
      const msg = (body && body.message) || `HTTP ${res.status}`;
      throw new GitHubError(msg, res.status, body);
    }
    return body;
  }

  /* ------------------------------------------------------------- reads --- */

  /** Anonymous, CDN-backed read. Returns null on 404. */
  async readRaw(path, { cacheBust = true } = {}) {
    const url = `${RAW}/${this.owner}/${this.repo}/${this.branch}/${encodePath(path)}` +
      (cacheBust ? `?t=${Date.now()}` : '');
    const res = await this.fetch(url, { cache: 'no-store' });
    if (res.status === 404) return null;
    if (!res.ok) throw new GitHubError(`raw read failed: HTTP ${res.status}`, res.status, null);
    return res.text();
  }

  async readJson(path, fallback = null) {
    // Authenticated path first: it always sees the newest commit (no CDN lag).
    if (this.token) {
      const f = await this.getFile(path);
      if (!f) return fallback;
      try { return JSON.parse(f.content); } catch { return fallback; }
    }
    const text = await this.readRaw(path);
    if (text === null) return fallback;
    try { return JSON.parse(text); } catch { return fallback; }
  }

  /** Contents API read. Returns {content, sha, path, size} or null. */
  async getFile(path) {
    try {
      const r = await this.request(
        `/repos/${this.slug}/contents/${encodePath(path)}?ref=${encodeURIComponent(this.branch)}`,
      );
      if (Array.isArray(r)) throw new GitHubError('Path is a directory', 400, null);
      return {
        path: r.path,
        sha: r.sha,
        size: r.size,
        content: r.encoding === 'base64' ? b64ToUtf8(r.content) : (r.content ?? ''),
      };
    } catch (e) {
      if (e.status === 404) return null;
      throw e;
    }
  }

  /** List a directory. Returns [] when it does not exist. */
  async listDir(dir) {
    try {
      const r = await this.request(
        `/repos/${this.slug}/contents/${encodePath(dir)}?ref=${encodeURIComponent(this.branch)}`,
      );
      if (!Array.isArray(r)) return [];
      return r.map((f) => ({ name: f.name, path: f.path, sha: f.sha, size: f.size, type: f.type }));
    } catch (e) {
      if (e.status === 404) return [];
      throw e;
    }
  }

  /* ------------------------------------------------------------ writes --- */

  /**
   * Create or update a file. Reads the current sha when not supplied.
   * @returns {Promise<{sha:string, commit:string, path:string}>}
   */
  async putFile(path, content, { message, sha, author } = {}) {
    if (!this.canWrite) throw new GitHubError('NO_TOKEN', 401, null);
    let currentSha = sha;
    if (currentSha === undefined) {
      const existing = await this.getFile(path);
      currentSha = existing?.sha;
    }
    const body = {
      message: message || `chore(data): update ${path}`,
      content: utf8ToB64(typeof content === 'string' ? content : JSON.stringify(content, null, 2)),
      branch: this.branch,
    };
    if (currentSha) body.sha = currentSha;
    if (author) body.committer = author;
    const r = await this.request(`/repos/${this.slug}/contents/${encodePath(path)}`, {
      method: 'PUT',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(body),
    });
    return { sha: r.content?.sha, commit: r.commit?.sha, path: r.content?.path || path };
  }

  async putJson(path, obj, opts = {}) {
    return this.putFile(path, JSON.stringify(obj, null, 2) + '\n', opts);
  }

  async deleteFile(path, { message, sha } = {}) {
    if (!this.canWrite) throw new GitHubError('NO_TOKEN', 401, null);
    let currentSha = sha;
    if (!currentSha) {
      const existing = await this.getFile(path);
      if (!existing) return false;
      currentSha = existing.sha;
    }
    await this.request(`/repos/${this.slug}/contents/${encodePath(path)}`, {
      method: 'DELETE',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ message: message || `chore(data): delete ${path}`, sha: currentSha, branch: this.branch }),
    });
    return true;
  }

  /**
   * Commit many files atomically via the Git Data API (blobs → tree → commit).
   * Much cheaper than N Contents-API calls and avoids partial writes.
   * @param {Array<{path:string, content:string}>} files
   */
  async commitFiles(files, message = 'chore(data): batch update') {
    if (!this.canWrite) throw new GitHubError('NO_TOKEN', 401, null);
    if (!files.length) return null;

    const ref = await this.request(`/repos/${this.slug}/git/ref/heads/${encodeURIComponent(this.branch)}`);
    const baseCommitSha = ref.object.sha;
    const baseCommit = await this.request(`/repos/${this.slug}/git/commits/${baseCommitSha}`);

    const tree = [];
    for (const f of files) {
      if (f.delete) { tree.push({ path: f.path, mode: '100644', type: 'blob', sha: null }); continue; }
      const blob = await this.request(`/repos/${this.slug}/git/blobs`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ content: utf8ToB64(f.content), encoding: 'base64' }),
      });
      tree.push({ path: f.path, mode: '100644', type: 'blob', sha: blob.sha });
    }

    const newTree = await this.request(`/repos/${this.slug}/git/trees`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ base_tree: baseCommit.tree.sha, tree }),
    });
    const commit = await this.request(`/repos/${this.slug}/git/commits`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ message, tree: newTree.sha, parents: [baseCommitSha] }),
    });
    await this.request(`/repos/${this.slug}/git/refs/heads/${encodeURIComponent(this.branch)}`, {
      method: 'PATCH',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ sha: commit.sha, force: false }),
    });
    return commit.sha;
  }

  /* ------------------------------------------------------------- misc ---- */

  /** Verify the token and its scope. Returns {login, scopes, canPush}. */
  async verify() {
    const repo = await this.request(`/repos/${this.slug}`);
    let login = null;
    if (this.token) {
      try { login = (await this.request('/user'))?.login ?? null; }
      catch { login = null; } // fine-grained tokens may not expose /user
    }
    return {
      login,
      repo: repo.full_name,
      private: repo.private,
      defaultBranch: repo.default_branch,
      canPush: Boolean(repo.permissions?.push),
    };
  }
}

const encodePath = (p) => String(p).split('/').filter(Boolean).map(encodeURIComponent).join('/');
const num = (v) => (v === null || v === undefined ? null : Number(v));

